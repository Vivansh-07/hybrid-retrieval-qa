"""paper_sncs/ (the full paper in the Springer Nature template) stays in step with paper_full/.

paper_sncs/main.tex and references.bib are generated by scripts/make_sncs.py; if a chapter's
abstract, the title, the authors, the Declarations or the bibliography change in the full paper,
the script has to be run again, and these tests say so.
"""

import importlib.util
import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SNCS = REPO / "paper_sncs"
_spec = importlib.util.spec_from_file_location("make_sncs", REPO / "scripts" / "make_sncs.py")
make_sncs = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(make_sncs)


def test_generated_files_are_up_to_date():
    for name, text in make_sncs.build().items():
        assert (SNCS / name).read_text(encoding="utf-8") == text, (
            f"paper_sncs/{name} is out of date: run python scripts/make_sncs.py")


def test_template_files_are_present():
    for name in ("sn-jnl.cls", "sn-apacite.bst"):
        assert (SNCS / name).exists(), f"paper_sncs/{name} (Springer Nature template) is missing"


def test_every_chapter_and_citation_resolves():
    main = (SNCS / "main.tex").read_text(encoding="utf-8")
    chapters = re.findall(r"\\input\{\.\./paper_full/sections/([^}]+)\}", main)
    assert chapters == make_sncs.CHAPTERS
    text = main + "".join((REPO / "paper_full" / "sections" / f"{c}.tex").read_text(encoding="utf-8")
                          for c in chapters)
    cited = {k.strip() for group in re.findall(
        r"\\(?:[Pp]arencite|[Tt]extcite|citep|citet|citeauthor|citeyear|cite)\*?\{([^}]+)\}", text)
        for k in group.split(",")} - {"#1"}   # the preamble's \newcommand{\parencite}[1]{\citep{#1}}
    keys = set(re.findall(r"^@\w+\{([^,]+),", (SNCS / "references.bib").read_text(encoding="utf-8"), flags=re.M))
    assert cited and cited <= keys, f"cited but not in paper_sncs/references.bib: {sorted(cited - keys)}"


def test_every_reference_has_an_author():
    # three entries once had none, and both styles then printed the title in the author's place
    entries = make_sncs.parse_bib((REPO / "paper_full" / "references.bib").read_text(encoding="utf-8"))
    missing = [key for _, key, fields in entries if not dict(fields).get("author", "").strip()]
    assert not missing, f"references without an author: {missing}"


def test_bibliography_is_plain_bibtex():
    """Every entry of the full paper is there, with no biblatex-only type or field left for BibTeX to ignore."""
    bib = (SNCS / "references.bib").read_text(encoding="utf-8")
    full = (REPO / "paper_full" / "references.bib").read_text(encoding="utf-8")
    assert len(re.findall(r"^@\w+\{", bib, flags=re.M)) == len(re.findall(r"^@\w+\{", full, flags=re.M))
    assert not re.search(r"^@(online|thesis)\{", bib, flags=re.M)
    assert not re.search(r"^\s*(date|journaltitle|eprint|eprinttype|urldate|eid)\s*=", bib, flags=re.M)
    # a dated entry keeps its year
    assert len(re.findall(r"^\s*date\s*=", full, flags=re.M)) == len(re.findall(r"^\s*year\s*=", bib, flags=re.M))
