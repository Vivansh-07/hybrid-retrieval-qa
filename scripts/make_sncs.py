#!/usr/bin/env python
"""Builds paper_sncs/: the full paper in the Springer Nature journal template, for SN Computer Science.

    python scripts/make_sncs.py

The chapters are not copied: paper_sncs/main.tex inputs ../paper_full/sections/*.tex, so a chapter
rewritten for the full paper is rewritten here too. Two files are generated from the full paper:

  paper_sncs/main.tex        the sn-jnl preamble; title, authors and e-mail addresses from
                             paper_full/main.tex; the abstract and keywords from
                             sections/00_abstract.tex (Springer wants them as \\abstract{} and
                             \\keywords{} before \\maketitle); the chapters; and the Declarations
                             from paper_full/main.tex.
  paper_sncs/references.bib  paper_full/references.bib converted from biblatex to BibTeX for the
                             template's APA style (option sn-apa: apacite with sn-apacite.bst).

sn-jnl.cls and sn-apacite.bst are the Springer Nature template package (December 2024 version),
unchanged. GitHub builds the PDF (workflow paper_sncs); tests/test_sncs.py checks that the two
generated files are up to date, so after editing the full paper, run this script again.
"""
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
FULL = REPO / "paper_full"
OUT = REPO / "paper_sncs"
CHAPTERS = ["01_introduction", "02_literature_review", "03_methodology", "04_experimental_setup",
            "05_results", "06_failure_analysis", "07_discussion", "08_limitations_conclusion"]

PREAMBLE = r"""%% Generated by scripts/make_sncs.py from paper_full/: do not edit by hand.
%% The full paper in the Springer Nature journal template (sn-jnl, December 2024), APA references.
\documentclass[pdflatex,sn-apa]{sn-jnl}

\usepackage{graphicx}
\graphicspath{{../paper/figures/}}
\usepackage{amsmath,amssymb,amsfonts}
\usepackage{xcolor}
\usepackage{booktabs,tabularx,multirow,makecell}
\usepackage{tikz}
\usetikzlibrary{arrows.meta,fit,positioning}
\usepackage{algorithm}
\usepackage[noend]{algpseudocode}

\renewcommand{\algorithmicrequire}{\textbf{Input:}}
\renewcommand{\algorithmicensure}{\textbf{Output:}}
\newcolumntype{L}{>{\raggedright\arraybackslash}X}
\newcolumntype{P}[1]{>{\raggedright\arraybackslash}p{#1}}
% the chapters cite with biblatex's commands; apacite (natbibapa) provides the natbib ones
\newcommand{\parencite}[1]{\citep{#1}}
\newcommand{\textcite}[1]{\citet{#1}}

\raggedbottom
"""


def strip_comments(tex: str) -> str:
    return "\n".join(re.sub(r"(?<!\\)%.*", "", line) for line in tex.splitlines())


def one_line(text: str) -> str:
    return " ".join(text.split())


def title_and_authors(main: str):
    """Title, [(first, last, e-mail)], department, (organisation, city, state, country) from paper_full/main.tex."""
    title = re.search(r"\\title\{\\textbf\{(.*?)\}\}\s*\n", main, flags=re.S).group(1)
    title = one_line(title.replace("\\\\", " "))
    block = re.search(r"\\author\{(.*?)\}\s*\n\\date", main, flags=re.S).group(1)
    lines = [one_line(re.sub(r"\\normalsize|\\\\(\[[^]]*\])?", " ", line)) for line in block.splitlines()]
    names = [n.strip() for n in lines[0].split(",")]
    emails = re.findall(r"\\texttt\{([^}@]+@[^}]+)\}", block)
    if len(names) != len(emails):
        raise SystemExit(f"{len(names)} authors but {len(emails)} e-mail addresses in paper_full/main.tex")
    department = next(line for line in lines if line.startswith("Department"))
    place = next(line for line in lines if "University" in line)
    organisation, city, state, country = [p.strip() for p in place.split(",")]
    authors = [(*name.rsplit(" ", 1), email) for name, email in zip(names, emails)]
    return title, authors, department, (organisation, city, state, country)


def abstract_and_keywords():
    tex = strip_comments((FULL / "sections" / "00_abstract.tex").read_text(encoding="utf-8"))
    body = tex.split("\\begin{abstract}", 1)[1].split("\\end{abstract}", 1)[0]
    text, _, keywords = body.partition("\\textbf{Keywords:}")
    text = one_line(text.replace("\\noindent", " ").replace("\\medskip", " "))
    return text, [k.strip() for k in one_line(keywords).split(";") if k.strip()]


def declarations(main: str) -> str:
    """The Declarations of paper_full/main.tex, without its table-of-contents line."""
    block = main.split("\\section*{Declarations}", 1)[1].split("\\clearpage", 1)[0]
    block = re.sub(r"\\addcontentsline\{[^}]*\}\{[^}]*\}\{[^}]*\}\n?", "", block)
    return block.strip() + "\n"


def make_main() -> str:
    main = (FULL / "main.tex").read_text(encoding="utf-8")
    title, authors, department, (organisation, city, state, country) = title_and_authors(main)
    abstract, keywords = abstract_and_keywords()
    out = [PREAMBLE, "\\begin{document}\n",
           f"\\title[{title.split(':')[0]}]{{{title}}}\n"]
    out += [f"\\author[1]{{\\fnm{{{first}}} \\sur{{{last}}}}}\\email{{{email}}}\n" for first, last, email in authors]
    out += [f"\\affil[1]{{\\orgdiv{{{department}}}, \\orgname{{{organisation}}}, "
            f"\\orgaddress{{\\city{{{city}}}, \\state{{{state}}}, \\country{{{country}}}}}}}\n\n",
            f"\\abstract{{{abstract}}}\n\n",
            f"\\keywords{{{', '.join(keywords)}}}\n\n",
            "\\maketitle\n\n"]
    out += [f"\\input{{../paper_full/sections/{c}}}\n" for c in CHAPTERS]
    out += ["\n\\backmatter\n\n\\section*{Declarations}\n\n", declarations(main),
            "\n\\bibliography{references}\n\n\\end{document}\n"]
    return "".join(out)


# --- biblatex -> BibTeX --------------------------------------------------------------------------

def parse_bib(text: str) -> list:
    """[(type, key, [(field, value)])], values without their outer braces, in file order."""
    entries = []
    for m in re.finditer(r"@(\w+)\{([^,\s]+),", text):
        i, depth = m.end(), 1
        while depth:                                    # find the entry's closing brace
            depth += {"{": 1, "}": -1}.get(text[i], 0)
            i += 1
        body, fields, j = text[m.end():i - 1], [], 0
        for f in re.finditer(r"(\w+)\s*=\s*\{", body):
            if f.start() < j:
                continue
            k, depth = f.end(), 1
            while depth:
                depth += {"{": 1, "}": -1}.get(body[k], 0)
                k += 1
            fields.append((f.group(1).lower(), body[f.end():k - 1]))
            j = k
        entries.append((m.group(1).lower(), m.group(2), fields))
    return entries


def to_bibtex(kind: str, fields: list):
    f = dict(fields)
    out = {}
    if "date" in f:
        year, *rest = f.pop("date").split("-")
        out["year"] = year
        if rest:
            out["month"] = str(int(rest[0]))
    if "journaltitle" in f:
        out["journal"] = f.pop("journaltitle")
    if "eid" in f and "pages" not in f:
        out["pages"] = f.pop("eid")
    f.pop("eid", None)
    eprint, eprinttype = f.pop("eprint", None), f.pop("eprinttype", "").lower()
    urldate = f.pop("urldate", None)
    if kind == "thesis":
        kind = "mastersthesis" if f.pop("type", "phdthesis").startswith("master") else "phdthesis"
        out["school"] = f.pop("institution", "")
    elif kind == "online":
        kind = "misc"
        if eprint and eprinttype == "arxiv":
            out["howpublished"] = f"arXiv preprint arXiv:{eprint}"
        if urldate:
            out["lastchecked"] = urldate
    return kind, {**f, **out}


def make_bib() -> str:
    lines = ["% Generated by scripts/make_sncs.py from paper_full/references.bib (biblatex) for BibTeX\n"
             "% and the template's APA style: do not edit by hand.\n"]
    for kind, key, fields in parse_bib((FULL / "references.bib").read_text(encoding="utf-8")):
        kind, f = to_bibtex(kind, fields)
        width = max(len(name) for name in f)
        body = ",\n".join(f"  {name:<{width}} = {{{value}}}" for name, value in f.items())
        lines.append(f"\n@{kind}{{{key},\n{body}\n}}\n")
    return "".join(lines)


def build() -> dict:
    return {"main.tex": make_main(), "references.bib": make_bib()}


def main() -> int:
    OUT.mkdir(exist_ok=True)
    for name, text in build().items():
        (OUT / name).write_text(text, encoding="utf-8", newline="\n")
        print("written", OUT / name)
    return 0


if __name__ == "__main__":
    sys.exit(main())
